"""
Build rila_pirin_zarr/results/: one place to find every finished year of both series, plus a status page.

    results/
      STATUS.md                          every year x both series: done / running / downloading / queued
      ncar_14levels/YYYY/               -> data/runs/YYYY/outputs      (ERA5 NCAR/CDS, 14 levels 600-1000 hPa)
      ncar_14levels/t_mean_monthly/     -> t_mean_monthly_YYYY.tif     (12 bands, for QGIS)
      edh_5levels/YYYY/                 -> data/runs_edh/YYYY/outputs  (ERA5 Earth Data Hub, 600/700/850/925/1000)
      edh_5levels/t_mean_monthly/       -> t_mean_monthly_YYYY.tif

Only years with a DONE marker (all months + checks passed) get a link. Links are relative, so they work on the host
and in the container (/app). Standard library only; safe to rerun at any time (rebuilds links + STATUS.md).

    python rila_pirin_zarr/scripts/update_results.py          # once
    python rila_pirin_zarr/scripts/update_results.py --every 600   # keep refreshing (used in the background)
"""
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]          # rila_pirin_zarr/
DATA = ROOT / 'data'
OUT = ROOT / 'results'
YEARS = range(1985, 2026)
SERIES = {
    'ncar_14levels': dict(runs=DATA / 'runs', loop=sorted((DATA / 'logs').glob('downscale_all_2*.log')),
                          title='NCAR series: ERA5 14 pressure levels 600-1000 hPa (NCAR NCSS + CDS/NCAR single levels)'),
    'edh_5levels': dict(runs=DATA / 'runs_edh', loop=sorted((DATA / 'logs').glob('downscale_all_edh_*.log')),
                        title='EDH series: ERA5 from Earth Data Hub, 5 pressure levels 600/700/850/925/1000 hPa'),
}


def loop_state(logs):
    """Last loop message per year, e.g. {1985: 'downscaling'} from '[time] 1985 downscaling'."""
    st = {}
    for f in logs:
        for line in f.read_text(errors='replace').splitlines():
            parts = line.split('] ', 1)
            if len(parts) == 2 and parts[1][:4].isdigit():
                y, _, msg = parts[1].partition(' ')
                st[int(y)] = msg.strip()
    return st


def era5_state(y):
    d = DATA / 'era5_600-1000hPa' / str(y)
    if (d / 'ERA5_OK').exists():
        return 'ERA5 ready'
    m = d / 'state' / 'manifest.jsonl'
    if m.exists():
        n = sum('"status": "written"' in l for l in m.read_text(errors='replace').splitlines())
        return f'ERA5 downloading ({n} parts written)'
    return 'ERA5 queued'


def year_info(run):
    s = run / 'outputs' / 'year_summary.json'
    if not s.exists():
        return '', ''
    j = json.loads(s.read_text())
    fin = str(j.get('finished', ''))[:16]
    rng = (j.get('monthly_geotiff') or {}).get('range')
    return fin, (f'{rng[0]:.1f} .. {rng[1]:.1f}' if rng else '')


def relink(link, target):
    if link.is_symlink() or link.exists():
        if link.is_symlink() and os.readlink(link) == os.path.relpath(target, link.parent):
            return
        link.unlink()
    link.symlink_to(os.path.relpath(target, link.parent))


def build():
    OUT.mkdir(exist_ok=True)
    rows, counts = {}, {}
    for name, cfg in SERIES.items():
        sdir, tdir = OUT / name, OUT / name / 't_mean_monthly'
        tdir.mkdir(parents=True, exist_ok=True)
        loop = loop_state(cfg['loop'])
        n_done = 0
        for y in YEARS:
            run = cfg['runs'] / str(y)
            if (run / 'DONE').exists():
                n_done += 1
                fin, rng = year_info(run)
                status = f'**done** {fin}'
                relink(sdir / str(y), run / 'outputs')
                tif = run / 'outputs' / 'geotiff' / f't_mean_monthly_{y}.tif'
                if tif.exists():
                    relink(tdir / tif.name, tif)
            else:
                for stale in (sdir / str(y), tdir / f't_mean_monthly_{y}.tif'):
                    if stale.is_symlink():
                        stale.unlink()
                rng = ''
                if (run / 'FAILED').exists():
                    status = '**FAILED** (see logs)'
                elif loop.get(y) == 'downscaling' or any((run / 'logs').glob('run_year_*.log')):
                    # loop logs can go silent (stdout of a closed session), the run folder can't
                    done_m = len(list((run / 'outputs' / 'months').glob('*.json')))
                    status = f'downscaling ({done_m}/12 months)'
                elif name == 'ncar_14levels':
                    status = era5_state(y)
                else:
                    status = 'queued'
            rows.setdefault(y, {})[name] = (status, rng)
        counts[name] = n_done

    now = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    L = [f'# Rila-Pirin downscaling 1985-2025: results and status', '',
         f'Auto-generated by `scripts/update_results.py`, last update **{now}** (refreshes every 10 min).', '',
         '| series | years done | where |', '|---|---:|---|']
    for name, cfg in SERIES.items():
        L.append(f'| {cfg["title"]} | **{counts[name]} / {len(YEARS)}** | `results/{name}/` |')
    L += ['', '**Use the NCAR series as the final dataset.** The EDH series is the fast one; its alpine zone is ~0.5 K',
          'colder (fewer levels). Do not mix the two series in one time series (jumps between years).', '',
          'Each finished year `results/<series>/YYYY/` contains:', '',
          '- `downscaled/down.zarr`: hourly, 1002 clusters: t, p, q, u, v, w, ws, wd, SW, SW_direct, SW_diffuse, '
          'LW, tp',
          '- `downscaled/daily.zarr`: daily per cluster: t_mean/min/max, tp_sum, q_mean/min/max, SW(_direct/_diffuse)_mean, '
          'LW_mean, p_mean, u/v/w_mean, ws_mean/max, wd_vector_mean',
          '- `geotiff/t_mean_monthly_YYYY.tif`: monthly mean temperature [degC] on the 30 m grid, 12 bands '
          '(all of them also in `results/<series>/t_mean_monthly/`)',
          '- `year_summary.json`, `months/*.json`: QA and timings; clusters/terrain: `df_centroids.pck`, `ds_param.zarr`',
          '', '| year | NCAR 14 levels | t range [degC] | EDH 5 levels | t range [degC] |', '|---|---|---|---|---|']
    for y in YEARS:
        a, b = rows[y]['ncar_14levels'], rows[y]['edh_5levels']
        L.append(f'| {y} | {a[0]} | {a[1]} | {b[0]} | {b[1]} |')
    L += ['', 'Notes: EDH 1985 was downloaded with all 19 EDH levels (before the 5-level decision); only the levels '
          'around each cluster enter the calculation, so its values equal a 5-level run. Decisions and history: '
          '`LOG.md`. Setup and commands: `README.md`.', '']
    tmp = OUT / 'STATUS.md.tmp'
    tmp.write_text('\n'.join(L))
    tmp.replace(OUT / 'STATUS.md')
    return counts


if __name__ == '__main__':
    every = int(sys.argv[sys.argv.index('--every') + 1]) if '--every' in sys.argv else 0
    while True:
        try:
            c = build()
            print(datetime.now(timezone.utc).strftime('%H:%M'), c, flush=True)
        except Exception as e:                 # never let the refresher die on a half-written file
            print('update failed:', repr(e), flush=True)
        if not every:
            break
        time.sleep(every)
