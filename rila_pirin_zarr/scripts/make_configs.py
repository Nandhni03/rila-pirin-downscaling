"""
Write the configs of the FABDEM run (container paths, /app = rila-pirin-downscaling):

    python rila_pirin_zarr/scripts/make_configs.py [--years 1985 2025]

    config/config_terrain.yml            terrain + clusters + horizon, once (prepare_terrain.py)
    config/years/config_YYYY.yml         downscaling of one year (run_year.py), terrain caches shared
    config/era5/config_era5_YYYY.yml     ERA5 600-1000 hPa download of one year (zarr_workflow/era5_download)
    config/years_edh/config_YYYY.yml     the same year from Earth Data Hub (5 levels), separate series in data/runs_edh

Every setting is a decision in LOG.md (2026-11-05). Rerunning overwrites the configs (they hold no state).
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = '/app/rila_pirin_zarr'
NCAR_SURF = {2005, 2020, 2025}   # single levels from NCAR; all other years from the CDS (1985 moved on 2026-11-06, LOG.md)
PLEVELS = '[600,650,700,750,775,800,825,850,875,900,925,950,975,1000]'

ERA5_LOCAL = """\
    path: {APP}/data/era5_600-1000hPa/{year}   # made by era5_download.py (config/era5/config_era5_{year}.yml)
    product: reanalysis
    timestep: 1h
    plevels: {PLEVELS}   # all ERA5 levels 600-1000 hPa
    download_threads: 4
    data_repository: local                # prepared store: only checked (workflow.check_era5_store)"""

# EDH series (separate product, never mixed with the NCAR 14-level series): EDH serves 600/700/850/925/1000 only
ERA5_EDH = """\
    path: {APP}/data/era5_edh/{year}      # EDH fetch (fork fetch_era5_edh), resumable from edh_blocks/
    product: reanalysis
    timestep: 1h
    plevels: {PLEVELS}   # EDH has 600/700/850/925/1000 in this range: the ones the terrain needs
    download_threads: 4
    data_repository: edh
    edh_output_format: zarr
    edh_max_concurrency: 8"""

TOPO = """\
# Rila-Pirin, FABDEM 30 m, {what}
# Generated by rila_pirin_zarr/scripts/make_configs.py; decisions in rila_pirin_zarr/LOG.md (2026-11-05).
project:
  name: Rila-Pirin FABDEM {name}
  description: FABDEM 30 m EPSG:32634, rectangle mask, k=1000 in 4 elevation groups (coef 0.5/1/1.5/2), features elev6 aspect2, {era_desc}
  authors:
    - Nandhni, MSc GIS, West University of Timisoara
  date: 2026-11-05
  directory: {directory}
  start: {year}-01-01
  end: {year}-12-31
  split:
    IO: False
    time: 1
    space: None
  climate: era5
  extent:                                 # empty: from the DEM (+0.4 deg)
  parallelization:
    downscaling_method: multicore
    setting:
      multicore:
        CPU_cores: 24                     # machine: 32 threads, 62 GB
      dask:
        n_workers: 4
        threads_per_worker: 1
        memory_target_fraction: 0.95
        memory_limit: 1.2GB

climate:
  precip_lapse_rate: True
  era5:
{era5_block}
    realtime: False
    rm_daily: False
    zarr_store: ERA5.zarr

dem:
  path: {APP}/data/dem
  file: dem.tif                           # FABDEM V1-2, 30 m, EPSG:32634 (~/fabdem/fabdem_32634_30m.tif)
  epsg: 32634
  horizon_increments: 10
  solar_position_method: nrel_numpy

sampling:
  method: toposub
  toposub:
    clustering_method: minibatchkmean
    n_clusters: 1000                      # 149/427/241/185 per group (ceil -> 1002)
    random_seed: 2
    clustering_features: {{'x':1, 'y':1, 'elevation':6, 'slope':1, 'aspect_cos':2, 'aspect_sin':2, 'svf':1}}
    clustering_mask: {APP}/data/dem/mask.tif
    clustering_groups: {APP}/data/dem/groups.tif                 # 1 <800, 2 800-1500, 3 1500-2000, 4 >=2000 m
    clustering_group_weights: {APP}/data/dem/group_weights.csv   # pixels x coef 0.5/1/1.5/2, sum exactly 1

toposcale:
  interpolation_method: idw
  LW_terrain_contribution: True

outputs:
  directory: outputs
  variables: all
  file:
    clean_outputs: False                  # must stay False: True deletes the outputs folder
    clean_FSM: False
    df_centroids: df_centroids.pck
    ds_param: ds_param.zarr
    ds_solar: ds_solar.zarr
    da_horizon: da_horizon.zarr
    landform: landform.tif
    downscaled_pt: down_pt_*.nc           # not used (zarr_store is set)
    zarr_store: down.zarr                 # hourly, one store per year
    zarr_store_start: {year}-01-01
    zarr_store_end: {year}-12-31

clean_up:
  rm_tmp_dirs: True
"""

ERA5 = """\
# ERA5 hourly for the Rila-Pirin FABDEM run, {year}: 14 pressure levels 600-1000 hPa + the 7 single-level variables
# TopoPyScale needs, into one Zarr store. Generated by rila_pirin_zarr/scripts/make_configs.py.
# Settings as zarr_workflow/era5_download/config_era5_2020.yml (why: that folder's LOG.md / REPORT.md).
period:
  start: {year}-01-01
  end: {year}-12-31

area:                          # DEM extent + 0.4 deg, snapped to the 0.25 deg grid (same as all Rila-Pirin stores)
  north: 43.0
  west: 22.25
  south: 40.75
  east: 24.75

levels: [600, 650, 700, 750, 775, 800, 825, 850, 875, 900, 925, 950, 975, 1000]
plev_vars: [z, t, u, v, q, r]
surf_vars: [z_surf, d2m, sp, strd, ssrd, tp, t2m]

source:
  plev: ncar
  surf: {surf}                    # {surf_why}

cds:
  workers: 2
  max_items_plev: 60000
  max_items_surf: 121000
  poll_seconds: 30
  max_retries: 5
  backoff_seconds: 120
  request_timeout_hours: 24

ncar:
  workers: 12                  # per lane; 2 lanes run at once (run_era5_lane.sh) -> 24 requests to NCAR
  base_url: https://thredds.rda.ucar.edu/thredds/ncss/grid/files/g/d633000/e5.oper.an.pl
  max_retries: 5
  backoff_seconds: 60
  timeout_seconds: 600

paths:
  store: {APP}/data/era5_600-1000hPa/{year}/ERA5.zarr
  raw: {APP}/data/era5_600-1000hPa/{year}/raw
  state: {APP}/data/era5_600-1000hPa/{year}/state
  logs: {APP}/data/era5_600-1000hPa/{year}/logs

store:
  time_chunk: 744
"""


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--years', type=int, nargs=2, default=[1985, 2025])
    a = p.parse_args()
    (ROOT / 'config' / 'years').mkdir(parents=True, exist_ok=True)
    (ROOT / 'config' / 'era5').mkdir(parents=True, exist_ok=True)
    (ROOT / 'config' / 'years_edh').mkdir(parents=True, exist_ok=True)
    local = lambda y: ERA5_LOCAL.format(APP=APP, year=y, PLEVELS=PLEVELS)
    edh = lambda y: ERA5_EDH.format(APP=APP, year=y, PLEVELS=PLEVELS)
    (ROOT / 'config' / 'config_terrain.yml').write_text(TOPO.format(
        what='terrain parameters, clusters and horizon (once, shared by all years).',
        name='terrain', directory=f'{APP}/data/terrain', year=2020, APP=APP, era5_block=local(2020),
        era_desc='ERA5 (NCAR) 14 levels 600-1000 hPa'))
    for y in range(a.years[0], a.years[1] + 1):
        (ROOT / 'config' / 'years' / f'config_{y}.yml').write_text(TOPO.format(
            what=f'year {y}: downscaling into Zarr (terrain caches linked from data/terrain).',
            name=str(y), directory=f'{APP}/data/runs/{y}', year=y, APP=APP, era5_block=local(y),
            era_desc='ERA5 (NCAR) 14 levels 600-1000 hPa'))
        (ROOT / 'config' / 'years_edh' / f'config_{y}.yml').write_text(TOPO.format(
            what=f'year {y}, EDH series (5 levels): downscaling into Zarr (terrain caches linked from data/terrain).',
            name=f'{y} EDH', directory=f'{APP}/data/runs_edh/{y}', year=y, APP=APP, era5_block=edh(y),
            era_desc='ERA5 (Earth Data Hub) 5 levels 600/700/850/925/1000 hPa'))
        surf = 'ncar' if y in NCAR_SURF else 'cds'
        why = ('NCAR OPeNDAP (started before the switch)' if surf == 'ncar' else
               'CDS, one request per year: NCAR OPeNDAP overloaded since 2026-11-05 19 UTC (LOG.md)')
        (ROOT / 'config' / 'era5' / f'config_era5_{y}.yml').write_text(
            ERA5.format(year=y, APP=APP, surf=surf, surf_why=why))
    print(f'configs written for {a.years[0]}-{a.years[1]} + terrain')


if __name__ == '__main__':
    main()
